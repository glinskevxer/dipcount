"""Writing the schema out as a document, from a book built by the migrations.

The point of building it rather than reading the migration text is that the
migrations are a history and the schema is a state. Sixteen steps in, what a
table looks like is the sum of the step that made it and every step that has
altered it since, and nobody can hold that in their head. So a book is built
from nothing, the schema is read back out of sqlite, and that is what the
document says.

In ``--check`` mode it says whether the file on disk is the schema the code
would produce, which is what turns a forgotten migration into a red build
rather than a surprise.
"""

from __future__ import annotations

import sys
from pathlib import Path

from dipcount.store.book import Book
from dipcount.store.migrate import upgrade
from dipcount.store.migrations import MIGRATIONS, latest
from dipcount.tools import source

DOCUMENT = "docs/SCHEMA.md"


def path() -> Path:
    """Where the generated schema document lives."""
    return source.project_root() / DOCUMENT


def _built() -> Book:
    book = Book.memory()
    upgrade(book)
    return book


def _table_lines(book: Book, table: str) -> list[str]:
    out = [
        f"### {table}",
        "",
        "| column | type | not null | default |",
        "| --- | --- | --- | --- |",
    ]
    for row in book.all(f"PRAGMA table_info({table})"):
        default = row["dflt_value"]
        out.append(
            f"| {row['name']} | {row['type'] or 'any'} |"
            f" {'yes' if row['notnull'] else ''} | {default if default is not None else ''} |",
        )
    out.append("")
    keys = book.all(f"PRAGMA foreign_key_list({table})")
    if keys:
        out.append("Points at: " + ", ".join(f"{one['from']} to {one['table']}" for one in keys))
        out.append("")
    names = [str(one["name"]) for one in book.all(f"PRAGMA index_list({table})")]
    if names:
        out.append("Indexed: " + ", ".join(sorted(names)))
        out.append("")
    return out


def document() -> str:
    """The whole schema as a book built from the migrations would have it."""
    book = _built()
    try:
        lines = [
            "# The schema",
            "",
            "Generated by `python -m dipcount.tools.schema_dump`. Edit the",
            "migrations, not this file.",
            "",
            f"Schema version {latest()}, built by {len(MIGRATIONS)} migrations.",
            "",
            "## the steps",
            "",
            "| step | name |",
            "| --- | --- |",
        ]
        lines.extend(f"| {one.number:03d} | {one.name} |" for one in MIGRATIONS)
        lines.extend(["", "## the tables", ""])
        for table in book.tables():
            lines.extend(_table_lines(book, table))
        return "\n".join(lines).rstrip() + "\n"
    finally:
        book.close()


def tables() -> list[str]:
    """Every table the built schema holds."""
    book = _built()
    try:
        return book.tables()
    finally:
        book.close()


def write() -> Path:
    """Write the document and say where it went."""
    made = path()
    made.parent.mkdir(parents=True, exist_ok=True)
    made.write_text(document())
    return made


def matches() -> bool:
    """Whether the file on disk is the schema the code would build."""
    made = path()
    return made.exists() and made.read_text() == document()


def main(argv: list[str] | None = None) -> None:
    """Write the schema document, or check the one on disk."""
    args = sys.argv[1:] if argv is None else argv
    if "--check" in args:
        if matches():
            print(f"schema_dump: ok (schema {latest()}, {len(tables())} tables)")
            sys.exit(0)
        print(f"schema_dump: {DOCUMENT} is not the schema the migrations build")
        sys.exit(1)
    print(f"schema_dump: wrote {write()}")


if __name__ == "__main__":
    main()
